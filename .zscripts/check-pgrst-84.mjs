import { readFileSync } from "node:fs"
const env = readFileSync("/home/z/my-project/.env", "utf8")
const KEY = env.match(/^SUPABASE_SERVICE_ROLE_KEY=(.+)$/m)[1].trim().replace(/^"|"$/g, "")
const URL = env.match(/^SUPABASE_URL=(.+)$/m)[1].trim().replace(/^"|"$/g, "")
const r = await fetch(`${URL}/rest/v1/customer_notifications?select=id&limit=1`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
console.log("REST select status:", r.status, await r.text())
const o = await fetch(`${URL}/rest/v1/`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
const od = await o.json()
const names = (od.definitions ? Object.keys(od.definitions) : []).filter(n => n.includes("notification"))
console.log("openapi tables with 'notification':", names.join(", ") || "NONE")
